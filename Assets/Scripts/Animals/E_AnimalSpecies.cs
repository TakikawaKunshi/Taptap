/// <summary>
/// 动物物种。
/// 策划案第五章把候选生物分成 MVP 与扩展两类：Demo 先做青蛙、蚯蚓、蜗牛、蚂蚁和蜘蛛五种，
/// 覆盖捕食者、分解者、植物消耗者、搬运者和空间改变者；
/// 已追加奶蛙；鱼类、沙蚕和麻雀仍保留为扩展。
/// 命名与 E_PlantSpecies 一样使用通用类别而不是具体外观，方便同一物种换皮。
/// </summary>
public enum E_AnimalSpecies
{
    // ---- MVP 五种 ----
    Frog,       // 青蛙，核心捕食者，雨行，吃小型无脊椎动物
    Earthworm,  // 蚯蚓，分解者，吃余屑与枯萎植物，松土并提供炼化材料
    Snail,      // 蜗牛，植物消耗者，吃藻类、苔藓和蘑菇
    Ant,        // 蚂蚁，搬运者，搬运种子并消耗余屑与孢子
    Spider,     // 蜘蛛，非天气型捕食者，结网捕食蚂蚁等小型动物

    // ---- 扩展预留，首版不实现 ----
    Fish,       // 鱼类，需要水面寻路
    Sandworm,   // 沙蚕，连接水陆边界
    Sparrow,    // 麻雀，远距离播种
    // 保持原有枚举值，兼容场景和投放卡片的序列化数据。
    MilkFrog    // 已实现：奶蛙，顶级捕食者与搬运者
}
