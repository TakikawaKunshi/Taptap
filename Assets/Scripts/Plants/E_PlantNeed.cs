/// <summary>
/// 植物向天气提出的条件询问。
/// 策划案要求天气只提供机会、不替植物做决定，所以这里只描述"需要什么"，
/// 由天气层负责回答条件是否成立，植物据此再结合空间与自身状态决定结果。
/// </summary>
public enum E_PlantNeed
{
    Light,      // 光照，晴天成立，种子植物据此获得光合标记
    Moisture,   // 潮湿，雨天成立，孢子植物据此增长
    Heat,       // 热，晴天成立，地表与菌类据此衰减
    Fungi       // 繁菌，雨天成立，已有余屑的地块据此更容易长蘑菇
}