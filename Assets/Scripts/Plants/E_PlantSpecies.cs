/// <summary>
/// 植物物种。与策划案的分类一一对应：前三个是孢子植物，后两个是种子植物。
/// 命名使用通用类别而不是具体外观，方便同一物种换皮而不改逻辑。
/// </summary>
public enum E_PlantSpecies
{
    Algae,        // 藻类，附着在积水或湿润地表
    Moss,         // 苔藓，作为地表覆盖可以和主体植物共存
    Mushroom,     // 蘑菇，依靠余屑生长，死亡后是余屑的主要来源
    Gymnosperm,   // 裸子植物，用晴雨交替的成长回合
    Angiosperm    // 被子植物，用晴雨交替的成长回合
}